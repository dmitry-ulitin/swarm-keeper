// Writes src/icons/icons.ts from icons.json: the SVG source of each listed Material Symbols
// Rounded icon (outline, weight 400, @material-symbols/svg-400). Run `pnpm icons:build` after
// editing icons.json; icons.spec.ts checks the file is current and every svgIcon is listed.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const root = new URL('..', import.meta.url);
const require = createRequire(new URL('package.json', root));
const names = JSON.parse(readFileSync(new URL('icons.json', root), 'utf8'));
const svg = (name) =>
  readFileSync(require.resolve(`@material-symbols/svg-400/rounded/${name}.svg`), 'utf8').trim();

const lines = [
  '// Generated by scripts/build-icons.mjs from icons.json. Do not edit: run `pnpm icons:build`.',
  '',
  '/** Registered icons: name → SVG source (Material Symbols Rounded, outline, weight 400). */',
  'export const ICONS: Readonly<Record<string, string>> = {',
  ...[...names].sort().map((name) => `  ${name}:\n    ${JSON.stringify(svg(name))},`),
  '};',
  '',
];
writeFileSync(new URL('src/icons/icons.ts', root), lines.join('\n'));
console.log(`icons.ts: ${names.length} icons`);
